create table alert_groups (
    id bigint generated by default as identity primary key,
    status varchar(20) not null default 'OPEN',
    probable_root_service_id bigint not null,
    first_alert_at timestamptz not null,
    last_alert_at timestamptz not null,
    incident_id bigint,
    constraint chk_alert_groups_status check (status in ('OPEN', 'CONFIRMED', 'DISMISSED')),
    constraint chk_alert_groups_time_range check (first_alert_at <= last_alert_at),
    constraint fk_alert_groups_root_service foreign key (probable_root_service_id) references business_services(id),
    constraint fk_alert_groups_incident foreign key (incident_id) references incidents(id)
);

alter table alerts add column group_id bigint;
alter table alerts add constraint fk_alerts_group foreign key (group_id) references alert_groups(id);

create index idx_alerts_unassigned_occurred_id on alerts (occurred_at, id) where group_id is null;
create index idx_alerts_group_occurred_id on alerts (group_id, occurred_at, id);
create index idx_alert_groups_last_alert on alert_groups (last_alert_at desc, id desc);
create index idx_alert_groups_status_last_alert on alert_groups (status, last_alert_at desc, id desc);
create index idx_alert_groups_root_last_alert on alert_groups (probable_root_service_id, last_alert_at desc, id desc);
create index idx_alert_groups_open_interval on alert_groups (last_alert_at, first_alert_at) where status = 'OPEN';
