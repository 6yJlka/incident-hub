create table alerts (
    id bigint generated by default as identity primary key,
    source varchar(100) not null,
    external_id varchar(255) not null,
    business_service_id bigint not null,
    signal_type varchar(20) not null,
    severity varchar(10) not null,
    occurred_at timestamptz not null,
    received_at timestamptz not null,
    description varchar(2000) not null,
    constraint uk_alerts_source_external_id unique (source, external_id),
    constraint fk_alerts_business_service foreign key (business_service_id) references business_services(id),
    constraint chk_alerts_signal_type check (signal_type in ('AVAILABILITY', 'ERROR_RATE', 'LATENCY', 'SATURATION')),
    constraint chk_alerts_severity check (severity in ('CRITICAL', 'WARNING', 'INFO')),
    constraint chk_alerts_source_not_blank check (length(trim(source)) > 0),
    constraint chk_alerts_external_id_not_blank check (length(trim(external_id)) > 0),
    constraint chk_alerts_description_not_blank check (length(trim(description)) > 0)
);

create index idx_alerts_business_service_id on alerts (business_service_id);
