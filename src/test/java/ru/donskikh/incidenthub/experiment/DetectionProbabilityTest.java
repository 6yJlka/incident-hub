package ru.donskikh.incidenthub.experiment;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import ru.donskikh.incidenthub.experiment.io.ScenarioJsonCodec;
import ru.donskikh.incidenthub.experiment.scenario.DetectionModel;
import ru.donskikh.incidenthub.experiment.scenario.ScenarioGenerationCommand;
import ru.donskikh.incidenthub.experiment.scenario.ScenarioGenerator;
import ru.donskikh.incidenthub.experiment.scenario.ScenarioParameters;
import ru.donskikh.incidenthub.experiment.scenario.ScenarioSample;
import ru.donskikh.incidenthub.experiment.scenario.TruthLabel;

import java.util.Map;
import java.util.TreeMap;

import static org.assertj.core.api.Assertions.*;
import static ru.donskikh.incidenthub.experiment.ExperimentFixtures.*;

class DetectionProbabilityTest {
    private final ScenarioJsonCodec codec = new ScenarioJsonCodec();

    private ScenarioParameters detection(ScenarioParameters p, double probability, Map<Long, Double> overrides) {
        return new ScenarioParameters(p.start(), p.injectionPeriod(), p.failures(), p.propagationProbability(), p.propagationDelay(),
                new DetectionModel(p.detection().defaultDistribution(), p.detection().overrides(), probability, overrides), p.noise(), p.signals());
    }

    private ScenarioSample generate(ScenarioParameters parameters, long seed) {
        return new ScenarioGenerator().generate(new ScenarioGenerationCommand(graph(3, edge(2, 1), edge(3, 2)), parameters, seed));
    }

    @ParameterizedTest
    @ValueSource(longs = {1, 42, 99})
    void probabilityOnePreservesLegacyAlertsTruthAndGraphs(long seed) throws Exception {
        // Snapshots generated by commit 89e6b7b before detection filtering was introduced.
        try (var stream = getClass().getResourceAsStream("/experiment/model-1/scenario-" + seed + ".json")) {
            assertThat(stream).isNotNull();
            var legacy = codec.read(stream.readAllBytes());
            var current = new ExperimentGenerator().generate(legacy.parameters());
            assertThat(current.observation()).isEqualTo(legacy.observation());
            assertThat(current.truth()).isEqualTo(legacy.truth());
            assertThat(current.trueGraph()).isEqualTo(legacy.trueGraph());
            assertThat(current.modelVersion()).isEqualTo("1");
            assertThat(codec.read(codec.write(current))).isEqualTo(current);
        }
    }

    @ParameterizedTest
    @ValueSource(booleans = {false, true})
    void decreasingProbabilityOnlyHidesUnchangedAlertsEvenWithOverridesAndNoise(boolean withOverrides) {
        var p = ExperimentDefaults.parameters().scenario();
        for (long seed = 0; seed < 50; seed++) {
            ScenarioSample previous = null;
            for (double probability : new double[]{1, .8, .4, 0}) {
                var sample = generate(detection(p, probability, withOverrides ? Map.of(2L, .5) : Map.of()), seed);
                if (previous != null) {
                    assertThat(previous.alerts()).containsAll(sample.alerts());
                    assertThat(sample.truth().failures()).isEqualTo(previous.truth().failures());
                    var prior = previous;
                    sample.alerts().forEach(alert -> assertThat(sample.truth().byAlertKey().get(alert.externalKey()))
                            .isEqualTo(prior.truth().byAlertKey().get(alert.externalKey())));
                    assertThat(sample.alerts().stream().filter(a -> sample.truth().byAlertKey().get(a.externalKey()) instanceof TruthLabel.Noise).toList())
                            .isEqualTo(previous.alerts().stream().filter(a -> prior.truth().byAlertKey().get(a.externalKey()) instanceof TruthLabel.Noise).toList());
                }
                previous = sample;
            }
        }
    }

    @Test
    void silentIntermediateNodeDoesNotBlockPropagationAndCanOccurProbabilistically() {
        int witnesses = 0;
        for (long seed = 0; seed < 100; seed++) {
            var sample = generate(detection(parameters(), .5, Map.of()), seed);
            var services = sample.alerts().stream().map(a -> a.serviceId()).toList();
            if (services.contains(1L) && !services.contains(2L) && services.contains(3L)) witnesses++;
        }
        assertThat(witnesses).isGreaterThan(0);
        assertThat(generate(detection(parameters(), 1, Map.of(2L, 0.0)), 42).alerts())
                .extracting(a -> a.serviceId()).containsExactlyInAnyOrder(1L, 3L);
    }

    @Test
    void silentRootCanHaveDetectedDependents() {
        var sample = generate(detection(parameters(), 1, Map.of(1L, 0.0)), 42);
        assertThat(sample.alerts()).extracting(a -> a.serviceId()).containsExactlyInAnyOrder(2L, 3L);
        assertThat(sample.truth().failures()).isEqualTo(generate(parameters(), 42).truth().failures());
    }

    @Test
    void completelyUndetectedFailureSurvivesArchiveRoundTripWithoutAlerts() {
        var p = ExperimentDefaults.parameters();
        var parameters = new GenerationParameters(p.graph(), p.distortion(), p.spuriousEdgeType(), detection(parameters(), 0, Map.of()), 42);
        var scenario = new ExperimentGenerator().generate(parameters);
        assertThat(scenario.observation().alerts()).isEmpty();
        assertThat(scenario.truth().byAlertKey()).isEmpty();
        assertThat(scenario.truth().failures()).hasSize(1);
        assertThat(codec.read(codec.write(scenario))).isEqualTo(scenario);
    }

    @Test
    void zeroDefaultCanBeOverriddenPerServiceAndOverridesAreImmutable() {
        var probabilities = new TreeMap<Long, Double>();
        probabilities.put(3L, 1.0);
        var model = new DetectionModel(parameters().detection().defaultDistribution(), Map.of(), 0, probabilities);
        probabilities.clear();
        assertThat(model.probabilityOverrides()).containsEntry(3L, 1.0);
        assertThatThrownBy(() -> model.probabilityOverrides().clear()).isInstanceOf(UnsupportedOperationException.class);
        assertThat(generate(detection(parameters(), model.detectionProbability(), model.probabilityOverrides()), 42).alerts())
                .extracting(a -> a.serviceId()).containsExactly(3L);
    }

    @Test
    void legacyConfigurationGetsProbabilityOneAndEmptyOverrides() throws Exception {
        try (var stream = getClass().getResourceAsStream("/experiment/model-1/scenario-42.json")) {
            var document = tools.jackson.databind.json.JsonMapper.builder().build().readTree(stream.readAllBytes());
            var configuration = codec.readParameters(document.path("parameters").toString().getBytes(java.nio.charset.StandardCharsets.UTF_8));
            assertThat(configuration.scenario().detection().detectionProbability()).isEqualTo(1.0);
            assertThat(configuration.scenario().detection().probabilityOverrides()).isEmpty();
        }
    }

    @Test
    void rejectsInvalidProbabilitiesUnknownServicesAndNullJsonValues() {
        for (double invalid : new double[]{-.1, 1.1, Double.NaN, Double.POSITIVE_INFINITY}) {
            assertThatIllegalArgumentException().isThrownBy(() -> detection(parameters(), invalid, Map.of()));
            assertThatIllegalArgumentException().isThrownBy(() -> detection(parameters(), 1, Map.of(1L, invalid)));
        }
        assertThatIllegalArgumentException().isThrownBy(() -> detection(parameters(), 1, Map.of(0L, .5)));
        assertThatIllegalArgumentException().isThrownBy(() -> generate(detection(parameters(), 1, Map.of(4L, .5)), 42));
        var p = ExperimentDefaults.parameters();
        var configured = new GenerationParameters(p.graph(), p.distortion(), p.spuriousEdgeType(), detection(p.scenario(), .4, Map.of(1L, .5)), 42);
        assertThat(codec.readParameters(codec.writeParameters(configured))).isEqualTo(configured);
        String json = new String(codec.writeParameters(configured), java.nio.charset.StandardCharsets.UTF_8);
        assertThatThrownBy(() -> codec.readParameters(json.replace("\"detectionProbability\" : 0.4", "\"detectionProbability\" : null")
                .getBytes(java.nio.charset.StandardCharsets.UTF_8))).isInstanceOf(RuntimeException.class);
    }
}
